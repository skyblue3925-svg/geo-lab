import {
  buildAnnualFactRows,
  buildAnnualFactsMarkup,
  buildKoppenBreakdownMarkup,
  buildMonthlyFactorRows,
  buildMonthlyFactorsMarkup,
  buildReasonListMarkup,
  buildRuleTraceMarkup,
  buildSelectionContextMarkup,
  buildSelectionKoppenMarkup,
  buildSelectionSummaryText,
} from "./selection-card-view.mjs";

export function buildSelectionCardRenderModel({
  analysis,
  context,
  coordinateLabel,
  officialCode,
  graphCode,
  graphDisplayCode,
  details,
  graphDetails,
  comparisonNote,
  observedMode,
  isObservedOceanCell,
  highlandAssist,
  activeExamSpot,
  circulationPressureBand,
  circulationWind,
  showUpperCirculation,
  jetPresence,
  geostrophicContext,
  activeClimateDataset,
  selectedMonth,
  monthLabels,
  traceRows,
  letterRows,
  koppenColors,
}) {
  const graphDiffers = observedMode && graphCode !== officialCode;
  const highlandSummary = highlandAssist ? ` 해발 ${highlandAssist.elevation.toFixed(0)} m의 고도 효과가 이런 그래프 판정 차이를 만듭니다.` : "";
  const examSpotSummary = activeExamSpot ? ` 평가원에서 ${activeExamSpot.examCount}회 나온 기출 지점입니다.` : "";
  const monthLabel = monthLabels[selectedMonth - 1];
  const annualFactRows = buildAnnualFactRows({
    analysis,
    observedMode,
    officialCode,
    graphDisplayCode,
    highlandAssist,
    activeExamSpot,
    comparisonNote,
  });
  const factorRows = buildMonthlyFactorRows({
    analysis,
    observedMode,
    graphDisplayCode,
    highlandAssist,
    activeExamSpot,
    circulationPressureBand,
    circulationWind,
    showUpperCirculation,
    jetPresence,
    geostrophicContext,
  });

  return {
    labelText: `${context.title} · ${coordinateLabel}`,
    koppenMarkup: buildSelectionKoppenMarkup({
      officialCode,
      graphCode,
      graphDisplayCode,
      details,
      graphDetails,
      comparisonNote,
      observedMode,
      graphDiffers,
      activeExamSpot,
      koppenColors,
    }),
    summaryText: buildSelectionSummaryText({
      isObservedOceanCell,
      climateResolution: activeClimateDataset.resolution,
      observedMode,
      graphDiffers,
      officialCode,
      graphDisplayCode,
      comparisonNote,
      activeClimateDataset,
      monthLabel,
      circulationPressureBand,
      circulationWindLabel: circulationWind.label,
      highlandSummary,
      examSpotSummary,
      experimentalClassificationCode: analysis.classification.code,
    }),
    contextMarkup: buildSelectionContextMarkup({
      observedMode,
      context,
      officialCode,
      elevation: analysis.profile.elevation,
      graphDisplayCode,
      activeExamSpot,
      comparisonNote,
    }),
    breakdownMarkup: buildKoppenBreakdownMarkup(letterRows),
    annualFactsMarkup: buildAnnualFactsMarkup({
      isObservedOceanCell,
      climateResolution: activeClimateDataset.resolution,
      rows: annualFactRows,
    }),
    monthlyFactorsMarkup: buildMonthlyFactorsMarkup(factorRows),
    ruleTraceMarkup: buildRuleTraceMarkup(traceRows),
    reasonListMarkup: buildReasonListMarkup(analysis.reasons),
    graphDiffers,
  };
}
